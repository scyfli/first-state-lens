# --------------------------------------------------------------------------- formatting

def slugify(name: str) -> str:
    s = re.sub(r"\s+School District$", "", name.strip(), flags=re.I)
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def school_year(y: str) -> str:
    """'2026' -> '2025-26' (the DOE's 2026 is the school year that ended June 2026)."""
    n = int(y)
    return f"{n - 1}-{str(n)[-2:]}"


def pct(v) -> str:
    return NR if v is None else f"{v:.1f}%"


def count(v) -> str:
    if v is None:
        return NR
    return f"{v:,.0f}" if float(v).is_integer() else f"{v:,.1f}"


def money(v) -> str:
    return NR if v is None else f"${v:,.0f}"


def nice_date(iso: str | None) -> str:
    if not iso:
        return "date not published"
    y, m, d = (int(x) for x in iso.split("-"))
    months = ["January", "February", "March", "April", "May", "June", "July", "August",
              "September", "October", "November", "December"]
    return f"{months[m - 1]} {d}, {y}"


def ds_link(ds: str, name: str) -> str:
    return f'<a href="{PORTAL}{e(ds)}" rel="noopener">{e(name)} ({e(ds)})</a>'


