"""Generate one static report card page per Delaware LEA (district or charter school).

Reads:
  schools/data/schools-summary.json   (etl.sources.de_report_card)
  schools/data/educator-salary.json   (etl.sources.de_educator_salary)
Writes:
  schools/district/<slug>/index.html  one page per LEA in schools-summary.json
  schools/index.html                  the district table's static rows, between the
                                      DISTRICT-ROWS markers (each name links to its page)

Plain HTML, no client-side rendering: names, titles and every figure are in the markup.
Neutral by construction: the same fields in the same order for every LEA, the statewide
figure beside each one as a plain number, no rankings, labels or colours computed from
numbers. A missing or suppressed value prints "Not reported", never zero.

Run:  python3 -m etl.pages.school_district_pages               (after both pullers)
      python3 -m etl.pages.school_district_pages --print-sitemap (sitemap <url> lines only)
"""

