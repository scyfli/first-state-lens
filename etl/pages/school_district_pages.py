def index_rows(summary: dict) -> str:
    rows = []
    for d in sorted(summary["districts"], key=lambda x: x["district"].lower()):
        href = f"/schools/district/{slugify(d['district'])}/"
        rows.append(
            f'<tr><td><a href="{e(href)}" data-dc="{e(d["districtcode"])}"><strong>{e(d["district"])}</strong></a></td>'
            f'<td class="num">{e(count(d.get("enrollment")))}</td><td class="num">{e(pct(d.get("ela_proficient")))}</td>'
            f'<td class="num">{e(pct(d.get("math_proficient")))}</td><td class="num">{e(pct(d.get("chronic_absenteeism")))}</td>'
            f'<td class="num">{e(pct(d.get("grad_rate")))}</td></tr>')
    return ROWS_START + "\n" + "\n".join(rows) + "\n" + ROWS_END


def replace_between(text: str, start: str, end: str, block: str) -> str:
    if text.count(start) != 1 or text.count(end) != 1:
        raise RuntimeError(f"markers {start!r}/{end!r} must each appear exactly once")
    i, j = text.find(start), text.find(end)
    if i > j:
        raise RuntimeError(f"marker {end!r} comes before {start!r}")
    return text[:i] + block + text[j + len(end):]


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def sitemap_lines(summary: dict, salary: dict) -> str:
    lm = as_of(summary, salary)
    return "\n".join(f"  <url><loc>{SITE}{p}</loc><lastmod>{lm}</lastmod><priority>0.6</priority></url>"
                     for p in sorted(build_pages(summary, salary)))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate per-LEA school report card pages.")
    ap.add_argument("--print-sitemap", action="store_true", help="print sitemap <url> lines and exit")
    a = ap.parse_args(argv)
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    salary = json.loads(SALARY.read_text(encoding="utf-8"))
    if a.print_sitemap:
        print(sitemap_lines(summary, salary))
        return 0
    pages = build_pages(summary, salary)
    changed = 0
    for path, text in pages.items():
        changed += write_if_changed(ROOT / path.strip("/") / "index.html", text)
    idx = INDEX.read_text(encoding="utf-8")
    changed += write_if_changed(INDEX, replace_between(idx, ROWS_START, ROWS_END, index_rows(summary)))
    expected = {p.strip("/").split("/")[-1] for p in pages}
    stale = sorted(p.name for p in (ROOT / "schools" / "district").iterdir() if p.is_dir() and p.name not in expected)
    if stale:
        print(f"warning: pages with no LEA in the current data (not deleted): {', '.join(stale)}", file=sys.stderr)
    print(f"school district pages: {len(pages)} generated, {changed} files changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
