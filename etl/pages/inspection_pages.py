def violation_li(v: dict) -> str:
    code = '<span class="c">' + e(v["code"]) + "</span>" if v.get("code") else ""
    desc = e(v["description"]) if v.get("description") else "No description listed"
    return "<li>" + code + desc + "</li>"


def est_block(est: dict) -> str:
    if est.get("mobile"):
        addr = f"Mobile food unit, {est['city']}, DE. Street address not shown: a mobile unit's listed address can be a private home."
    else:
        addr_parts = [est["address"] or "Street address not listed", est["city"]]
        addr = ", ".join(addr_parts) + ", DE" + (f" {est['zip']}" if est.get("zip") else ", ZIP not listed")
    out = [f'    <article class="est" id="e-{e(est["id"])}">',
           f'      <h3>{e(est["name"])}</h3>',
           f'      <p class="addr">{e(addr)}</p>']
    for i in est["inspections"]:
        out.append(f'      <h4><time datetime="{e(i["date"])}">{e(nice(i["date"]))}</time> · {e(i["type"])} inspection</h4>')
        if i["violations"]:
            out.append("      <ul>" + "".join(violation_li(v) for v in i["violations"]) + "</ul>")
        else:
            out.append('      <p class="nv">No violation listed for this inspection in the state\'s file.</p>')
    out.append("    </article>")
    return "\n".join(out) + "\n"


def part_label(keys: list[str]) -> tuple[str, str]:
    """Return (human label, url slug) for a part made of these first-letter keys."""
    letters = [k for k in keys if k != "#"]
    rng = "" if not letters else (letters[0] if len(letters) == 1 else f"{letters[0]} to {letters[-1]}")
    if "#" in keys:
        label = f"numbers, symbols and {rng}" if rng else "numbers and symbols"
    else:
        label = rng
    return label, slugify(rng or "numbers-and-symbols")


def plan_parts(town: dict, budget: int) -> list[dict]:
    groups: dict[str, list[tuple[dict, str]]] = {}
    for est in town["establishments"]:
        groups.setdefault(letter_key(est["name"]), []).append((est, est_block(est)))
    parts: list[list[str]] = []
    cur: list[str] = []
    size = 0
    for k in sorted(groups, key=key_order):
        g = sum(len(b.encode("utf-8")) for _, b in groups[k])
        if cur and size + g > budget:
            parts.append(cur)
            cur, size = [], 0
        cur.append(k)
        size += g
    if cur:
        parts.append(cur)
    base = f"/inspections/{town['slug']}/"
    out = []
    for n, keys in enumerate(parts):
        label, slug = part_label(keys)
        out.append({"keys": keys, "label": label, "path": base if n == 0 else f"{base}{slug}/",
                    "groups": {k: groups[k] for k in keys}})
    return out


