def build_all(manifest: dict, towns: list[dict], budget: int = BUDGET) -> tuple[dict[str, str], list[list[str]]]:
    stamp = manifest["source_updated"]
    lo, hi = manifest["window"]["date_min"], manifest["window"]["date_max"]
    pages: dict[str, str] = {}
    search: list[list[str]] = []
    types: set[str] = set()
    for town in towns:
        parts = plan_parts(town, budget)
        for part in parts:
            pages[part["path"]] = town_page(town, part, parts, stamp, lo, hi)
            for k in part["keys"]:
                for est, _ in part["groups"][k]:
                    search.append([est["name"], "" if est.get("mobile") else (est["address"] or ""), est["city"], f"{part['path']}#e-{est['id']}",
                                   est["inspections"][0]["date"]])
                    types.update(i["type"] for i in est["inspections"])
    search.sort(key=lambda s: (s[0].casefold(), s[2].casefold(), s[1].casefold(), s[3]))
    pages["/inspections/"] = index_page(manifest, towns, sorted(types, key=str.casefold))
    return pages, search


def sitemap_with_block(text: str, paths: list[str], lastmod: str) -> str | None:
    start, end = "<!-- INSPECTIONS:START", "<!-- INSPECTIONS:END -->"
    if text.count(start) != 1 or text.count(end) != 1:
        return None
    i, j = text.find(start), text.find(end) + len(end)
    if i > j:
        raise RuntimeError("INSPECTIONS:END comes before INSPECTIONS:START in sitemap.xml")
    urls = "\n".join(f"  <url><loc>{SITE}{p}</loc><lastmod>{lastmod}</lastmod><priority>0.6</priority></url>" for p in paths)
    return text[:i] + f"<!-- INSPECTIONS:START (generated by etl/pages/inspection_pages.py) -->\n{urls}\n  {end}" + text[j:]


def write_if_changed(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def load(data_dir: Path = DATA) -> tuple[dict, list[dict]]:
    manifest = json.loads((data_dir / "manifest.json").read_text(encoding="utf-8"))
    towns = [json.loads((data_dir / "towns" / f"{t['slug']}.json").read_text(encoding="utf-8")) for t in manifest["towns"]]
    if not towns:
        raise RuntimeError("No towns in the inspections manifest; refusing to generate empty pages.")
    return manifest, towns


def main() -> int:
    manifest, towns = load()
    pages, search = build_all(manifest, towns)
    changed = 0
    for path, text in pages.items():
        size = len(text.encode("utf-8"))
        if size > HARD_LIMIT:
            print(f"WARNING: {path} is {size:,} bytes, above the {HARD_LIMIT:,} byte limit", file=sys.stderr)
        changed += write_if_changed(ROOT / path.strip("/") / "index.html", text)
    changed += write_if_changed(DATA / "search-index.json",
                                json.dumps(search, ensure_ascii=False, separators=(",", ":")) + "\n")
    # Remove generated pages for towns or parts that no longer exist (only files we generated).
    keep = {(ROOT / p.strip("/") / "index.html").resolve() for p in pages}
    for f in OUT.rglob("index.html"):
        if f.resolve() not in keep and GEN_MARK in f.read_text(encoding="utf-8"):
            f.unlink()
            changed += 1
            try:
                f.parent.rmdir()
            except OSError:
                pass
    sm = ROOT / "sitemap.xml"
    new = sitemap_with_block(sm.read_text(encoding="utf-8"), sorted(pages), manifest["source_updated"])
    if new is None:
        print("sitemap.xml has no INSPECTIONS markers yet; skipped (see docs/wiring/inspections.md)")
    else:
        changed += write_if_changed(sm, new)
    sizes = sorted(((len(t.encode('utf-8')), p) for p, t in pages.items()), reverse=True)[:3]
    print(f"inspection pages: {len(pages)} generated, {changed} files changed; largest: "
          + ", ".join(f"{p} {s:,} B" for s, p in sizes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
