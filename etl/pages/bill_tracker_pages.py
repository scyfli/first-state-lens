def group_of(number: str) -> str:
    """'HS 1 for HB 457' -> 'house-bills'. Substitutes go with the thing they substitute for."""
    m = re.match(r"([A-Z]+) \d+(?: for ([A-Z]+) \d+)?", number)
    if not m:
        raise ValueError(f"unrecognised bill number {number!r}")
    prefix = m.group(2) or m.group(1)
    chamber = {"H": "house", "S": "senate"}.get(prefix[:1])
    if chamber is None or prefix not in {"HB", "HR", "HCR", "HJR", "SB", "SR", "SCR", "SJR"}:
        raise ValueError(f"unrecognised bill number {number!r}")
    return f"{chamber}-{'bills' if prefix.endswith('B') else 'resolutions'}"


def nice_date(iso: str | None) -> str:
    if not iso:
        return ""
    d = datetime.date.fromisoformat(iso)
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def short_date(iso: str | None) -> str:
    if not iso:
        return ""
    d = datetime.date.fromisoformat(iso)
    return f"{d.strftime('%b')} {d.day}, {d.year}"


def as_of(manifest: dict) -> str:
    return (manifest.get("generated_at") or "")[:10]


