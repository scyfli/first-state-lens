def source_line(data: dict, manifest: dict) -> str:
    return (f'<p class="src">Source: <a href="{LISTING_PAGE}">Delaware General Assembly, All Legislation</a> '
            f'(legis.delaware.gov), {e(data["assembly_name"])}, read {nice_date(as_of(manifest))}. '
            f'Last actions come from each bill\'s action log on its official page. Each bill number links to that page. '
            f'<a href="/bill-tracker/data/bills-{data["session"]}.json">Download this list as JSON</a>.</p>')


def row(b: dict) -> str:
    g = group_of(b["number"])
    sponsor = (f'<a href="{e(b["sponsor_url"])}">{e(b["primary_sponsor"])}</a>' if b.get("sponsor_url") and b.get("primary_sponsor")
               else e(b["primary_sponsor"]) if b.get("primary_sponsor") else "No sponsor listed")
    if b.get("last_action"):
        last = f'{e(b["last_action"])}<small>{short_date(b.get("last_action_date"))}</small>'
    else:
        last = "No action listed"
    title = e(b["title"]) if b.get("title") else "No title listed"
    status = e(b["status"]) if b.get("status") else "No status listed"
    intro = short_date(b.get("introduced")) or "Not listed"
    return (f'<tr data-n="{b["order"]}" data-g="{g}" data-i="{e(b.get("introduced") or "")}" '
            f'data-d="{e(b.get("last_action_date") or "")}">'
            f'<th scope="row"><a href="{e(b["url"])}">{e(b["number"])}</a></th>'
            f'<td>{title}</td><td>{sponsor}</td><td>{e(b["chamber"])}</td><td>{intro}</td>'
            f'<td>{status}</td><td>{last}</td></tr>')


