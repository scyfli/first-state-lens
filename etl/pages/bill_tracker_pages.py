def counts_sentence(data: dict, bills: list[dict]) -> str:
    by: dict[str, int] = {}
    for b in bills:
        by[b["type"]] = by.get(b["type"], 0) + 1
    order = ["Bill", "Substitute", "Resolution", "Concurrent Resolution", "Joint Resolution"]
    plural = {"Bill": "bills", "Substitute": "substitutes", "Resolution": "simple resolutions",
              "Concurrent Resolution": "concurrent resolutions", "Joint Resolution": "joint resolutions"}
    parts = [f"{by[t]:,} {plural[t] if by[t] != 1 else plural[t][:-1]}" for t in order if by.get(t)]
    joined = ", ".join(parts[:-1]) + (" and " if len(parts) > 1 else "") + parts[-1] if parts else "none"
    return f"{len(bills):,} items: {joined}."


