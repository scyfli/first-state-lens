"""EPA SDWIS puller: one record per Delaware water system, with its violation list.

Feeds the per-system pages at /water/system/<pwsid>/ and the "Is my water safe?"
index at /water/ (both generated by etl/pages/water_pages.py).

Source: EPA Envirofacts SDWIS data service (efservice), keyless.
  - WATER_SYSTEM/PRIMACY_AGENCY_CODE/DE       every system Delaware regulates
  - GEOGRAPHIC_AREA/PRIMACY_AGENCY_CODE/DE    county and city served
  - VIOLATION/PRIMACY_AGENCY_CODE/DE          every violation on record
  - Contaminant and rule names: EPA ECHO lookup rest_lookups.sdwa_contaminants
    (one request; EPA's own wording, shown as published).

The Delaware filter (checked 2026-10-14, see docs/wiring/water-rebuild.md):
  * PRIMACY_AGENCY_CODE=DE is the regulatory state. It returns 1,362 systems, every
    PWSID starting "DE", and 1,766 violations. An independent filter,
    VIOLATION/PWSID/BEGINNING/DE, returns the identical 1,766 violation ids, and
    per-PWSID counts match. The puller re-checks this agreement on every run.
  * WATER_SYSTEM.STATE_CODE is the state of the system's mailing address, not where
    it operates: STATE_CODE=DE includes 91 out-of-state systems (Maryland,
    Pennsylvania, Florida and others) and misses 110 Delaware systems. The
    WATER_SYSTEM(STATE_CODE=DE) JOIN VIOLATION used by epa_sdwa_de.py returns 789
    rows, 56 of them out of state, and drops 1,033 Delaware violations.
  * VIOLATION/STATE_CODE/DE is silently national (about 2.1 million rows). Never use it.

Privacy: WATER_SYSTEM carries administrative contact fields (names, phones, emails,
street addresses) that often belong to private individuals. They are dropped in
memory by a whitelist; nothing from them is written to disk.

Neutrality: no score, rank or label. A violation's return-to-compliance date is
EPA's `rtc_date`, copied as is; when it is empty the record says so and we never
infer a status. Systems are ordered by PWSID.

License: US public domain (EPA). Cadence: EPA syncs SDWIS to Envirofacts about
quarterly; this puller runs weekly with the other dashboards.

Output:
  <out>/water-systems.json            data (deterministic; data_as_of only moves when content changes)
  <out>/water-systems-manifest.json   generated_at, source URLs, row counts

Run:
    python3 -m etl.sources.epa_sdwis_systems --out water/data
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import sys
from pathlib import Path

EF = "https://data.epa.gov/efservice"
WS_URL = f"{EF}/WATER_SYSTEM/PRIMACY_AGENCY_CODE/DE/ROWS/0:9999/JSON"
WS_COUNT_URL = f"{EF}/WATER_SYSTEM/PRIMACY_AGENCY_CODE/DE/COUNT/JSON"
GA_URL = f"{EF}/GEOGRAPHIC_AREA/PRIMACY_AGENCY_CODE/DE/ROWS/0:9999/JSON"
VIO_URL = f"{EF}/VIOLATION/PRIMACY_AGENCY_CODE/DE/ROWS/0:19999/JSON"
VIO_COUNT_URL = f"{EF}/VIOLATION/PRIMACY_AGENCY_CODE/DE/COUNT/JSON"
VIO_PREFIX_COUNT_URL = f"{EF}/VIOLATION/PWSID/BEGINNING/DE/COUNT/JSON"
CONTAM_URL = "https://echodata.epa.gov/echo/rest_lookups.sdwa_contaminants?output=JSON"
ECHO_REPORT = "https://echo.epa.gov/detailed-facility-report?fid="

OUT_DATA = "water-systems.json"
OUT_MANIFEST = "water-systems-manifest.json"

# Fields copied from WATER_SYSTEM. Everything else is discarded in memory.
WS_FIELDS = ("pwsid", "pws_name", "pws_type_code", "pws_activity_code", "pws_deactivation_date",
             "population_served_count", "primary_source_code")
# Named so tests can prove none of them reach the output.
CONTACT_FIELDS = ("admin_name", "email_addr", "phone_number", "alt_phone_number", "fax_number", "phone_ext_number",
                  "address_line1", "address_line2", "city_name", "zip_code", "org_name")

# Production plausibility floors (silent-zero guard). Live 2026-10-14: 1,362 / 1,766 / 203 / 871.
MIN_SYSTEMS = 1000
MIN_VIOLATIONS = 1000
MIN_ACTIVE_CWS = 150
MIN_CONTAMINANTS = 500

_ACRONYMS = {"LLC", "MHP", "II", "III", "IV", "USA", "US", "YMCA", "KOA", "RV", "DE", "AFB", "DNREC", "DOT", "LP", "LLP"}
_SMALL = {"of", "and", "the", "at", "on", "in", "for", "by"}


def _utc_now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def titlecase(raw: str | None) -> str | None:
    """EPA stores names in capitals. Make them readable; the raw name is kept alongside."""
    if raw is None:
        return None
    words = raw.split()
    out = []
    for i, w in enumerate(words):
        core = re.sub(r"[^A-Za-z]", "", w).upper()
        if core in _ACRONYMS and w.upper().strip("(),.#") == core:
            out.append(w.upper())
            continue
        lw = w.lower()
        if i > 0 and lw in _SMALL:
            out.append(lw)
            continue
        # capitalise the first letter of the word and of each part after - / ( .
        out.append(re.sub(r"(^|[-/(.&])([a-z])", lambda mm: mm.group(1) + mm.group(2).upper(), lw))
    return " ".join(out) or None


def county_name(raw: str | None) -> str | None:
    if not raw or not raw.strip():
        return None
    parts = [p.strip() for p in raw.split(",") if p.strip()]
    return " and ".join(parts) if parts else None


def _date(x) -> str | None:
    if not x:
        return None
    s = str(x).strip()
    if not re.match(r"^\d{4}-\d{2}-\d{2}", s):
        return None
    return s[:10]


def _int(x) -> int | None:
    try:
        n = int(float(x))
    except (TypeError, ValueError):
        return None
    return n if n > 0 else None


def parse_contaminants(payload: dict, minimum: int = MIN_CONTAMINANTS) -> dict[str, str]:
    try:
        rows = payload["Results"]["LuValues"]
    except (KeyError, TypeError):
        raise RuntimeError("ECHO sdwa_contaminants lookup returned no LuValues (silent-zero guard).")
    lu = {str(r["ValueCode"]).strip(): " ".join(str(r["ValueDescription"]).split())
          for r in rows if r.get("ValueCode") and r.get("ValueDescription")}
    if len(lu) < minimum:
        raise RuntimeError(f"ECHO contaminant lookup has {len(lu)} codes, expected at least {minimum} (silent-zero guard).")
    return lu


def build(ws_rows: list[dict], ga_rows: list[dict], vio_rows: list[dict], contaminants: dict[str, str], *,
          min_systems: int = MIN_SYSTEMS, min_violations: int = MIN_VIOLATIONS,
          min_active_cws: int = MIN_ACTIVE_CWS, min_contaminants: int = MIN_CONTAMINANTS) -> dict:
    """Pure transform. Raises instead of returning a thin or wrong dataset."""
    if len(ws_rows) < min_systems:
        raise RuntimeError(f"WATER_SYSTEM returned {len(ws_rows)} Delaware systems (silent-zero guard).")
    if len(vio_rows) < min_violations:
        raise RuntimeError(f"VIOLATION returned {len(vio_rows)} Delaware rows (silent-zero guard).")
    if len(contaminants) < min_contaminants:
        raise RuntimeError("contaminant lookup too small (silent-zero guard).")

    systems: dict[str, dict] = {}
    for r in ws_rows:
        w = {k: r.get(k) for k in WS_FIELDS}  # whitelist: contact fields never leave this line
        pid = (w["pwsid"] or "").strip()
        if not re.match(r"^DE[0-9A-Z]{7}$", pid):
            raise RuntimeError(f"non-Delaware or malformed PWSID {pid!r} in the Delaware set; refusing to write.")
        if pid in systems:
            raise RuntimeError(f"duplicate PWSID {pid} in WATER_SYSTEM")
        raw_name = " ".join((w["pws_name"] or "").split()) or None
        systems[pid] = {
            "pwsid": pid,
            "epa_name": raw_name,
            "name": titlecase(raw_name) or pid,
            "type": (w["pws_type_code"] or "").strip() or None,
            "activity": (w["pws_activity_code"] or "").strip() or None,
            "deactivated": _date(w["pws_deactivation_date"]),
            "population": _int(w["population_served_count"]),
            "source": (w["primary_source_code"] or "").strip() or None,
            "county": None,
            "city": None,
            "violations": [],
        }

    for g in ga_rows:
        pid = (g.get("pwsid") or "").strip()
        if pid not in systems:
            continue  # geography for a system outside the regulated set is ignored, never invented
        s = systems[pid]
        s["county"] = county_name(g.get("county_served"))
        city = (g.get("city_served") or "").strip()
        s["city"] = titlecase(city) if city else None

    for v in vio_rows:
        pid = (v.get("pwsid") or "").strip()
        if pid not in systems:
            raise RuntimeError(f"violation for {pid!r} is not in WATER_SYSTEM (Delaware); the filters disagree.")
        code = (v.get("contaminant_code") or "").strip() or None
        systems[pid]["violations"].append({
            "id": str(v.get("violation_id") or "").strip(),
            "begin": _date(v.get("compl_per_begin_date")),
            "end": _date(v.get("compl_per_end_date")),
            "returned_to_compliance": _date(v.get("rtc_date")),
            "contaminant_code": code,
            "contaminant": contaminants.get(code) if code else None,
            "category": (v.get("violation_category_code") or "").strip() or None,
            "health_based": (v.get("is_health_based_ind") or "").strip().upper() == "Y",
            "rule_code": (str(v.get("rule_code")).strip() if v.get("rule_code") is not None else None),
            "violation_code": (str(v.get("violation_code")).strip() if v.get("violation_code") is not None else None),
        })

    for s in systems.values():
        s["violations"].sort(key=lambda x: (x["begin"] or "", x["id"]), reverse=True)

    active_cws = [s for s in systems.values() if s["type"] == "CWS" and s["activity"] == "A"]
    if len(active_cws) < min_active_cws:
        raise RuntimeError(f"only {len(active_cws)} active community water systems (silent-zero guard).")

    page_systems = [s for s in systems.values()
                    if (s["type"] == "CWS" and s["activity"] == "A") or s["violations"]]
    page_systems.sort(key=lambda s: s["pwsid"])

    all_v = [v for s in systems.values() for v in s["violations"]]
    dates = [d for v in all_v for d in (v["begin"], v["end"], v["returned_to_compliance"]) if d]
    return {
        "totals": {
            "systems_on_record": len(systems),
            "community_active": len(active_cws),
            "systems_with_violations": sum(1 for s in systems.values() if s["violations"]),
            "violations_on_record": len(all_v),
            "health_based": sum(1 for v in all_v if v["health_based"]),
            "no_return_to_compliance_date": sum(1 for v in all_v if v["returned_to_compliance"] is None),
            "pages": len(page_systems),
            "latest_date_in_records": max(dates) if dates else None,
        },
        "source": {
            "name": "EPA Safe Drinking Water Information System (SDWIS), via Envirofacts",
            "filter": "PRIMACY_AGENCY_CODE = DE (systems Delaware regulates)",
            "water_system": WS_URL,
            "geographic_area": GA_URL,
            "violation": VIO_URL,
            "contaminant_names": CONTAM_URL,
            "system_report": ECHO_REPORT,
            "license": "US public domain",
        },
        "systems": page_systems,
    }


def dumps(d: dict) -> str:
    return json.dumps(d, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def _content_hash(d: dict) -> str:
    body = {k: v for k, v in d.items() if k != "data_as_of"}
    return hashlib.sha256(dumps(body).encode("utf-8")).hexdigest()


def write(out_dir: Path, data: dict, *, as_of: str, manifest_extra: dict) -> bool:
    """Write data + manifest. data_as_of keeps its old value when content is unchanged,
    so a no-change refresh leaves water-systems.json byte-identical. Returns True if data changed."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / OUT_DATA
    new_hash = _content_hash(data)
    keep_as_of = None
    if path.exists():
        try:
            old = json.loads(path.read_text(encoding="utf-8"))
            if _content_hash(old) == new_hash:
                keep_as_of = old.get("data_as_of")
        except (ValueError, OSError):
            keep_as_of = None
    final = dict(data)
    final["data_as_of"] = keep_as_of or as_of
    text = dumps(final)
    changed = not path.exists() or path.read_text(encoding="utf-8") != text
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    manifest = {
        "dashboard": "water-systems",
        "data_as_of": final["data_as_of"],
        "source_last_updated": None,
        "source_update_note": "Envirofacts publishes no per-table update stamp; EPA syncs SDWIS to Envirofacts about quarterly. latest_date_in_records is the newest date found in the records.",
        "sources": data["source"],
        "row_counts": data["totals"],
        "content_sha256": new_hash,
    }
    manifest.update(manifest_extra)
    (out_dir / OUT_MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return changed


def _json(url: str):
    from etl.lib.fetch import fetch  # imported here so tests need no network stack
    return json.loads(fetch(url).body)


def _count(url: str) -> int:
    rows = _json(url)
    return int(rows[0]["TOTALQUERYRESULTS"])


def pull(out_dir: Path) -> dict:
    ws_count = _count(WS_COUNT_URL)
    ws_rows = _json(WS_URL)
    if len(ws_rows) != ws_count:
        raise RuntimeError(f"WATER_SYSTEM rows {len(ws_rows)} != count {ws_count}; refusing a partial pull.")
    ga_rows = _json(GA_URL)
    vio_count = _count(VIO_COUNT_URL)
    prefix_count = _count(VIO_PREFIX_COUNT_URL)
    if vio_count != prefix_count:
        raise RuntimeError(f"Delaware filters disagree: PRIMACY_AGENCY_CODE=DE gives {vio_count} violations, "
                           f"PWSID BEGINNING DE gives {prefix_count}. Investigate before publishing.")
    vio_rows = _json(VIO_URL)
    if len(vio_rows) != vio_count:
        raise RuntimeError(f"VIOLATION rows {len(vio_rows)} != count {vio_count}; refusing a partial pull.")
    contaminants = parse_contaminants(_json(CONTAM_URL))
    data = build(ws_rows, ga_rows, vio_rows, contaminants)
    del ws_rows  # contact fields lived only in this list
    now = _utc_now()
    write(out_dir, data, as_of=now[:10], manifest_extra={
        "generated_at": now,
        "checks": {"water_system_count": ws_count, "violation_count_primacy": vio_count,
                   "violation_count_pwsid_prefix": prefix_count, "contaminant_codes": len(contaminants)},
    })
    return data


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Pull per-system Delaware drinking-water records (EPA SDWIS).")
    ap.add_argument("--out", type=Path, default=Path("water/data"))
    a = ap.parse_args(argv)
    d = pull(a.out)
    t = d["totals"]
    print(f"wrote {a.out}/{OUT_DATA}")
    print(f"  {t['systems_on_record']:,} Delaware public water systems on record; {t['community_active']} active community systems")
    print(f"  {t['violations_on_record']:,} violations on record ({t['health_based']:,} health-based, "
          f"{t['no_return_to_compliance_date']} with no return-to-compliance date)")
    print(f"  {t['pages']} system pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
