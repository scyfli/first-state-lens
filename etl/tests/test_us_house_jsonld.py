@pytest.mark.parametrize("damage", ["missing_start", "missing_end", "duplicate_start", "duplicate_end", "reversed"])
def test_ans_sch_001_builder_rejects_bad_markers(build_root: Path, damage: str) -> None:
    page = build_root / "candidates/us-house/index.html"
    text = page.read_text(encoding="utf-8")
    if damage == "reversed":
        text = text.replace(START, "TEMP_MARKER").replace(END, START).replace("TEMP_MARKER", END)
    else:
        marker = START if damage.endswith("start") else END
        text = text.replace(marker, "" if damage.startswith("missing") else marker * 2)
    page.write_text(text, encoding="utf-8")
    with pytest.raises(RuntimeError, match="marker"):
        cp.main()
    assert page.read_text(encoding="utf-8") == text


def test_ans_sch_001_main_refreshes_only_region_and_is_idempotent(build_root: Path) -> None:
    page = build_root / "candidates/us-house/index.html"
    before = page.read_text(encoding="utf-8")
    source = build_root / "candidates/data/us-house.json"
    data = json.loads(source.read_text(encoding="utf-8"))
    data["candidates"][0]["name_legal"] = "Updated name"
    source.write_text(json.dumps(data), encoding="utf-8")
    assert cp.main() == 0
    after = page.read_text(encoding="utf-8")
    assert json.loads(jsonld_payload(after))["itemListElement"][0]["item"]["name"] == "Updated name"
    assert after.split(START)[0] == before.split(START)[0]
    assert after.split(END)[1] == before.split(END)[1]
    saved_bytes, saved_mtime = page.read_bytes(), page.stat().st_mtime_ns
    assert cp.main() == 0
    assert page.read_bytes() == saved_bytes
    assert page.stat().st_mtime_ns == saved_mtime


