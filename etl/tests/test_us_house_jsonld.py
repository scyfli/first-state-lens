"""ANS-SCH-001: U.S. House ItemList is present in the static HTML."""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path

import pytest

from etl.pages import candidate_pages as cp

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "candidates/us-house/index.html"
DATA = ROOT / "candidates/data/us-house.json"
START = "<!-- USHOUSE-JSONLD:START (generated by etl/pages/candidate_pages.py) -->"
END = "<!-- USHOUSE-JSONLD:END -->"


def jsonld_payload(text: str) -> str:
    scripts = re.findall(r'<script\s+type="application/ld\+json">\s*(.*?)\s*</script>', text, re.S)
    assert len(scripts) == 1
    return scripts[0]


@pytest.fixture
def synthetic_data() -> dict:
    return {
        "office": {"name": "Test office", "chamber": "Test chamber"},
        "candidates": [
            {"name_legal": "Zoë Incumbent", "incumbent": True},
            {"name_legal": 'Alex "Challenger" </script>', "incumbent": False},
        ],
    }


def test_ans_sch_001_static_itemlist_matches_candidates() -> None:
    page = PAGE.read_text(encoding="utf-8")
    data = json.loads(DATA.read_text(encoding="utf-8"))
    payload = jsonld_payload(page)
    schema = json.loads(payload)
    assert list(schema) == ["@context", "@type", "name", "itemListElement"]
    assert schema["@context"] == "https://schema.org"
    assert schema["@type"] == "ItemList"
    assert schema["name"] == data["office"]["name"] + " — 2026 candidates"
    assert len(schema["itemListElement"]) == len(data["candidates"])
    for position, (entry, candidate) in enumerate(zip(schema["itemListElement"], data["candidates"]), 1):
        assert list(entry) == ["@type", "position", "item"]
        assert entry["@type"] == "ListItem"
        assert entry["position"] == position
        person = entry["item"]
        assert person["@type"] == "Person"
        assert person["name"] == candidate["name_legal"]
        assert person["seeks"] == {"@type": "PublicOffice", "name": data["office"]["name"]}
        assert ("memberOf" in person) == bool(candidate.get("incumbent"))
        keys = ["@type", "name"]
        if candidate.get("incumbent"):
            assert person["memberOf"] == {"@type": "GovernmentOrganization", "name": data["office"]["chamber"]}
            keys.append("memberOf")
        assert list(person) == keys + ["seeks"]
    assert payload in page.split("</head>", 1)[0]


def test_ans_sch_001_runtime_injection_removed() -> None:
    assert "injectJsonLd" not in PAGE.read_text(encoding="utf-8")


def test_ans_sch_001_render_is_pure_and_script_safe(synthetic_data: dict) -> None:
    original = copy.deepcopy(synthetic_data)
    block = cp.us_house_jsonld_block(synthetic_data)
    payload = jsonld_payload(block)
    assert "<" not in payload
    assert block.lower().count("</script>") == 1
    assert json.loads(payload) == {
        "@context": "https://schema.org",
        "@type": "ItemList",
        "name": "Test office — 2026 candidates",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "item": {
                "@type": "Person", "name": "Zoë Incumbent",
                "memberOf": {"@type": "GovernmentOrganization", "name": "Test chamber"},
                "seeks": {"@type": "PublicOffice", "name": "Test office"},
            }},
            {"@type": "ListItem", "position": 2, "item": {
                "@type": "Person", "name": 'Alex "Challenger" </script>',
                "seeks": {"@type": "PublicOffice", "name": "Test office"},
            }},
        ],
    }
    assert "Zoë" in payload and " — 2026 candidates" in payload
    assert payload == json.dumps(json.loads(payload), ensure_ascii=False, indent=2).replace("<", "\\u003c")
    assert synthetic_data == original
    assert cp.us_house_jsonld_block(synthetic_data) == block


def test_ans_sch_001_committed_region_matches_renderer() -> None:
    page = PAGE.read_text(encoding="utf-8")
    assert page.count(START) == page.count(END) == 1
    region = page[page.index(START):page.index(END) + len(END)]
    assert region == cp.us_house_jsonld_block(json.loads(DATA.read_text(encoding="utf-8")))
    assert page[page.index(END) + len(END):].startswith("\n</head>")


@pytest.mark.parametrize("field", ["name", "chamber", "name_legal"])
@pytest.mark.parametrize("invalid", [None, "", "missing"])
def test_ans_sch_001_required_names_fail_loudly(synthetic_data: dict, field: str, invalid: str | None) -> None:
    record = synthetic_data["candidates"][1] if field == "name_legal" else synthetic_data["office"]
    if invalid == "missing":
        del record[field]
    else:
        record[field] = invalid
    with pytest.raises(RuntimeError, match=field):
        cp.us_house_jsonld_block(synthetic_data)


